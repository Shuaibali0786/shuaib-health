// Compares each Windows visual baseline (-win32.png) with its Linux twin (-linux.png) and writes a Markdown report.
// Usage: node scripts/pixel-diff-report.mjs <output.md>
// Playbook rule 5: a baseline changes only with a pixel-diff report the owner has seen. The Windows files are
// never modified; this only reads. "Differs" means any colour channel is more than TOLERANCE/255 apart.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, relative } from "node:path";

const require = createRequire(import.meta.url);
const { PNG } = require("playwright-core/lib/utilsBundle");

const TOLERANCE = 16;
const root = new URL("../tests", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const out = process.argv[2];
if (!out) {
  console.error("usage: node scripts/pixel-diff-report.mjs <output.md>");
  process.exit(2);
}

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

function compare(winFile, linuxFile) {
  const a = PNG.sync.read(readFileSync(winFile));
  const b = PNG.sync.read(readFileSync(linuxFile));
  const sameSize = a.width === b.width && a.height === b.height;
  const width = Math.min(a.width, b.width);
  const height = Math.min(a.height, b.height);
  let differing = 0;
  let maxDelta = 0;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * a.width + x) * 4;
      const j = (y * b.width + x) * 4;
      let delta = 0;
      for (let c = 0; c < 3; c++) delta = Math.max(delta, Math.abs(a.data[i + c] - b.data[j + c]));
      if (delta > maxDelta) maxDelta = delta;
      if (delta > TOLERANCE) differing++;
    }
  }
  const compared = width * height;
  return { sameSize, win: `${a.width}x${a.height}`, linux: `${b.width}x${b.height}`, percent: (differing / compared) * 100, maxDelta };
}

const rows = [];
let missingTwin = 0;
for (const file of walk(root)) {
  if (!file.endsWith("-win32.png")) continue;
  const twin = file.replace(/-win32\.png$/, "-linux.png");
  const name = relative(root, file).replaceAll("\\", "/").replace(/-win32\.png$/, "");
  try {
    rows.push({ name, ...compare(file, twin) });
  } catch {
    missingTwin++;
    rows.push({ name, missing: true });
  }
}
rows.sort((x, y) => (y.percent ?? -1) - (x.percent ?? -1));

const compared = rows.filter((r) => !r.missing);
const sizeMismatch = compared.filter((r) => !r.sameSize).length;
const worst = compared[0];
const lines = [
  "# Visual baselines: Windows vs Linux pixel-diff report",
  "",
  `Generated by \`frontend/scripts/pixel-diff-report.mjs\`. A pixel counts as different when any colour channel is more than ${TOLERANCE}/255 apart (font smoothing alone causes small differences between platforms).`,
  "",
  `- Snapshots compared: **${compared.length}** (Windows file vs its new Linux file); Windows files without a Linux twin: **${missingTwin}**`,
  `- Different image size (full-page height or width): **${sizeMismatch}**`,
  worst ? `- Worst case: \`${worst.name}\` with **${worst.percent.toFixed(2)}%** of pixels different (max channel difference ${worst.maxDelta}/255)` : "",
  `- Median different-pixel share: **${compared.length ? compared[Math.floor(compared.length / 2)].percent.toFixed(2) : "0"}%**`,
  "",
  "| Snapshot | Windows size | Linux size | Different pixels | Max channel diff |",
  "|---|---|---|---|---|",
  ...rows.map((r) => (r.missing ? `| ${r.name} | | | **no Linux file** | |` : `| ${r.name} | ${r.win} | ${r.linux}${r.sameSize ? "" : " (differs)"} | ${r.percent.toFixed(2)}% | ${r.maxDelta} |`)),
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}: ${compared.length} compared, ${missingTwin} without a Linux twin`);
